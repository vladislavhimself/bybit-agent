"""Повторы новостей не идут к модели. Запуск из корня: python tests/test_dedup.py"""
import sys

sys.path.insert(0, ".")
sys.stdout.reconfigure(encoding="utf-8")
from bot.theme import dup_tokens, duplicate_of, stems  # noqa: E402

t0 = 1_800_000_000
ev = {"importance": 8, "direction": "bullish"}
recent = [(t0, dup_tokens("«Т-Технологии» планируют выкупить до 100% акций «Циана» по 993,05 рубля за бумагу"), ev, "n1"),
          (t0 + 60, dup_tokens("Путин подтвердил проведение трехсторонних переговоров по Украине в ОАЭ 10 ноября"), ev, "n2")]
dups = ["Т-Технологии планируют приобрести до 100% акций Циан, предложив акционерам по 993,05 рубля за бумагу",
        "🗞 «Т-Технологии» предложили акционерам ЦИАН выкупить до 100% акций платформы по 993,05 руб.",
        "Переговоры России, США и Украины по урегулированию пройдут 10 ноября в Абу-Даби, подтвердил Путин"]
for x in dups:
    assert duplicate_of(recent, x, t0 + 600), x
not_dups = ["Путин: переговоры с Украиной сорваны", "ЦИАН отчитался о росте выручки на 20%", "Т-Технологии объявили дивиденды",
            "Сбербанк повысил ставки по вкладам", "Путин провёл совещание с Совбезом по Абу-Даби",
            "«Т-Технологии» планируют выкупить до 100% акций «Циана» по 1 100 рублей за бумагу", "Переговоры по Украине в ОАЭ перенесены на 12 ноября"]
for x in not_dups:
    assert duplicate_of(recent, x, t0 + 600) is None, (x, stems(x))
assert duplicate_of(recent, dups[0], t0 + 4 * 3600) is None, "через 3 часа — уже не повтор"
assert duplicate_of(recent, "Циан", t0 + 600) is None, "короткий заголовок"
print("ВСЁ ОК")
